    const EMPTY_LOCALE_SNAPSHOT = { active: 'zh', locales: [], revision: 0 };
    let localeService = null;
    let layoutService = null;

    // Shared `{name}` interpolation so translate() and fill() behave the same.
    function interpolate(template, params) {
      const text = String(template);
      if (!params) return text;
      return text.replace(PLACEHOLDER_PATTERN, function replace(match, key) {
        return Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match;
      });
    }

    function makeTranslate(locale) {
      if (!locale) return function fallback(key, params) { return interpolate(ZH[key] || EN[key] || key, params); };
      let bound = null;
      try {
        bound = locale.bind(NS);
      } catch (error) {
        bound = null;
      }
      return function lookup(key, params) {
        let value = '';
        try {
          value = bound ? bound(key) : '';
        } catch (error) {
          value = '';
        }
        return interpolate(value || ZH[key] || EN[key] || key, params);
      };
    }

    let translate = makeTranslate(null);

    function fill(template, params) {
      return interpolate(template, params);
    }

    function activeLocale() {
      try {
        return localeService ? localeService.getLocale().active : 'zh';
      } catch (error) {
        return 'zh';
      }
    }

    function useLocaleTick() {
      const subscribe = useCallback(function subscribe(callback) {
        return localeService ? localeService.subscribe(callback) : function noop() {};
      }, []);
      const getSnapshot = useCallback(function snapshot() {
        return localeService ? localeService.getSnapshot() : EMPTY_LOCALE_SNAPSHOT;
      }, []);
      useSyncExternalStore(subscribe, getSnapshot);
    }
